#!/usr/bin/env node
// Builds apps/ios/www from the frozen game files in ../../drawrassic-park.
// The originals are only READ. Every change happens on the copy in www/.
//
//   node scripts/build-www.mjs                     -> store profile, latest version
//   node scripts/build-www.mjs --profile family    -> also bundles PeerJS (online play with friends)
//   node scripts/build-www.mjs --version 3.72      -> a specific version from versions.json
//
// Each text patch must match exactly once or the build stops, so a future game
// version that changes its markup can't silently ship a half-patched app.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(HERE, '..');                 // apps/ios
const REPO = path.resolve(APP, '../..');              // repo root
const GAME_ID = 'drawrassic-park';
const SRC = path.join(REPO, GAME_ID);
const OUT = path.join(APP, 'www');
const SHELL = path.join(APP, 'shell');
const SHELL_VERSION = 1;

const args = process.argv.slice(2);
const arg = (name, def) => { const i = args.indexOf('--' + name); return i >= 0 ? args[i + 1] : def; };
const profile = arg('profile', 'store');
if (!['store', 'family'].includes(profile)) fail(`unknown --profile ${profile} (use store or family)`);

function fail(msg) { console.error('build-www: ' + msg); process.exit(1); }
const read = p => fs.readFileSync(p, 'utf8');
const sha = buf => crypto.createHash('sha256').update(buf).digest('hex').slice(0, 16);

// ---------- pick the version ----------
const versions = JSON.parse(read(path.join(SRC, 'versions.json')));
const wanted = arg('version', null);
const entry = wanted ? versions.versions.find(v => v.v === wanted) : versions.versions[0];
if (!entry) fail(`version ${wanted} not in ${GAME_ID}/versions.json`);
const gameSrcPath = path.join(SRC, entry.file);
if (!fs.existsSync(gameSrcPath)) fail(`missing ${entry.file}`);

// ---------- helpers ----------
function replaceOnce(html, from, to, label) {
  const n = html.split(from).length - 1;
  if (n !== 1) fail(`patch "${label}" expected 1 match, found ${n}`);
  return html.replace(from, () => to);
}
function removeAll(html, re) { return html.replace(re, ''); }
function injectHead(html, tags, label) {
  const m = html.match(/<head[^>]*>/i);
  if (!m) fail(`no <head> in ${label}`);
  return html.replace(m[0], m[0] + '\n' + tags);
}

// ---------- clean output (www/ is generated, never edit it by hand) ----------
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'app', 'fonts'), { recursive: true });

// ---------- fonts: Fredoka (OFL) bundled instead of fonts.googleapis.com ----------
const fontDir = path.join(APP, 'node_modules/@fontsource/fredoka');
if (!fs.existsSync(fontDir)) fail('run "npm install" first (needs @fontsource/fredoka)');
let fontCss = '/* Fredoka, SIL Open Font License 1.1 (see fonts/OFL.txt). latin + latin-ext only; Chinese uses the system font. */\n';
for (const w of [400, 500, 600, 700]) {
  for (const sub of ['latin-ext', 'latin']) {
    const file = `fredoka-${sub}-${w}-normal.woff2`;
    fs.copyFileSync(path.join(fontDir, 'files', file), path.join(OUT, 'app', 'fonts', file));
    const block = read(path.join(fontDir, `${sub}-${w}.css`)).match(/unicode-range:[^;]+;/);
    fontCss += `@font-face{font-family:'Fredoka';font-style:normal;font-display:swap;font-weight:${w};src:url(fonts/${file}) format('woff2');${block ? block[0] : ''}}\n`;
  }
}
fs.copyFileSync(path.join(fontDir, 'LICENSE'), path.join(OUT, 'app', 'fonts', 'OFL.txt'));
fs.writeFileSync(path.join(OUT, 'app', 'fonts.css'), fontCss);

// ---------- shell files ----------
for (const f of ['app-shell.js', 'app-shell.css']) fs.copyFileSync(path.join(SHELL, f), path.join(OUT, 'app', f));
const config = {
  platform: 'ios',
  profile,                              // 'store' = App Store build, 'family' = TestFlight build with online play
  online: profile === 'family',         // PeerJS rooms + text chat (voice is always off in the app)
  game: GAME_ID,
  gameVersion: entry.v,
  gameFile: entry.file,
  schema: entry.schema,
  shellVersion: SHELL_VERSION,
};
fs.writeFileSync(path.join(OUT, 'app', 'app-config.js'),
  '/* generated by scripts/build-www.mjs */\nwindow.FAMILY_APP=Object.freeze(' + JSON.stringify(config) + ');\n');

const headTags = page =>
  `<link rel="stylesheet" href="app/fonts.css"><link rel="stylesheet" href="app/app-shell.css">` +
  `<script src="app/app-config.js"></script><script src="app/app-shell.js" data-page="${page}"></script>`;

// ---------- the game (copy + patches) ----------
const srcBuf = fs.readFileSync(gameSrcPath);
let game = srcBuf.toString('utf8');
game = replaceOnce(game, '<link rel="preconnect" href="https://fonts.googleapis.com">', '', 'google fonts preconnect');
game = replaceOnce(game, '<link href="https://fonts.googleapis.com/css2?family=Fredoka:wght@400;500;600;700&display=swap" rel="stylesheet">', '', 'google fonts css');
// web-app leftovers that point at files the app doesn't ship
game = removeAll(game, /<link rel="manifest"[^>]*>\s*/g);
game = removeAll(game, /<link rel="(?:apple-touch-icon|icon)"[^>]*>\s*/g);
game = injectHead(game, headTags('game'), entry.file);
if (/<(?:script|link)[^>]+(?:src|href)="https?:/i.test(game)) fail('the game copy still loads something from the internet');
fs.writeFileSync(path.join(OUT, entry.file), game);

// ---------- launcher, used only for its 🛟 Recover saves tool ----------
let launcher = read(path.join(SRC, 'index.html'));
launcher = removeAll(launcher, /<link rel="manifest"[^>]*>\s*/g);
launcher = removeAll(launcher, /<link rel="(?:apple-touch-icon|icon)"[^>]*>\s*/g);
launcher = injectHead(launcher, headTags('launcher'), 'index.html');
if (/<(?:script|link)[^>]+(?:src|href)="https?:/i.test(launcher)) fail('the launcher copy still loads something from the internet');
fs.writeFileSync(path.join(OUT, 'index.html'), launcher);
fs.writeFileSync(path.join(OUT, 'versions.json'), JSON.stringify({ game: GAME_ID, versions: [entry] }, null, 2));

// ---------- family profile: PeerJS for online play (MIT) ----------
if (profile === 'family') {
  fs.mkdirSync(path.join(OUT, 'vendor'), { recursive: true });
  fs.copyFileSync(path.join(REPO, 'vendor/peerjs.min.js'), path.join(OUT, 'vendor/peerjs.min.js'));
  fs.copyFileSync(path.join(REPO, 'vendor/LICENSE-peerjs-MIT.txt'), path.join(OUT, 'vendor/LICENSE-peerjs-MIT.txt'));
}

// ---------- build info (also proves the original file was untouched) ----------
const info = { ...config, sourceSha256: sha(srcBuf), builtAt: new Date().toISOString() };
fs.writeFileSync(path.join(OUT, 'app', 'build-info.json'), JSON.stringify(info, null, 2));
console.log(`www built: ${GAME_ID} v${entry.v} (${entry.file}), profile=${profile}, schema s${entry.schema}`);
